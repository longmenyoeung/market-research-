"""Export formula metadata only; synthetic inputs never become market output."""
import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / 'backend'))
from app.indicators.engine import calculate
from app.schemas.platform import IndicatorSettings


def main() -> None:
    x = np.arange(500)
    close = 100 + x*.01 + np.sin(x/10)
    sample = pd.DataFrame({'time': 1_700_006_400_000+x*3600000, 'open': close-.1,
                           'high': close+1, 'low': close-1, 'close': close,
                           'volume': 100+x%20, 'quote_volume': (100+x%20)*close})
    _, catalog = calculate(sample, IndicatorSettings(), '1h')
    sections = [
        '# Indicator methods',
        'Generated by `backend/scripts/export_indicator_docs.py` from the calculation catalog. '
        'This document contains formulas and default parameters, never live prices.',
        'All inputs are confirmed candles in ascending UTC order, with no interpolated gaps. '
        'Warm-up is the minimum number of input bars before a value may be returned; '
        'zero denominators, insufficient history or missing inputs can keep a value unavailable longer. '
        'EMA and iterative indicators depend on the loaded history and their stated seed. '
        'Open candles are chart-only until confirmed.',
        'Default units: prices in USDT, volume in base-contract units, oscillator values in '
        'their stated scale, volatility in annualized percent on a 365-day calendar. '
        'Evidence uses five capped groups (trend, structure, momentum, volume, context). '
        'Descriptive indicators within one group do not create independent confirmations.',
    ]
    for name, metadata in catalog.items():
        sections += [f'## {name}', f"Formula: {metadata['formula']}",
                     f"Parameters: `{json.dumps(metadata['parameters'], sort_keys=True)}`. "
                     f"Warm-up: {metadata['warmup']} bars. Inputs: {metadata['inputs']}. "
                     f"Group: {metadata['group']}.", metadata['interpretation']]
    sections += ['## Derived observations',
        'Volume spike: latest relative volume >=2. Price/volume disagreement: sign of the '
        '20-observation close change opposes the OBV change over the same observations. '
        'Volatility percentile uses the trailing sample, assigns half of ties to each side, '
        'and is compressed at <=20 or elevated at >=80. Scanner volatility warning separately '
        'uses configurable ATR/price (default 3%). Regime is trending at ADX>=25, otherwise ranging.',
        'VWAP resets at UTC midnight, using typical price (H+L+C)/3 and candle volume. '
        'The first loaded UTC day may be partial; this is not an exchange trade-by-trade VWAP.',
        'True volume profile is unavailable until reliable trade-at-price data is collected. '
        'Candle volume is never distributed over invented prices. '
        'See [drawing rules](drawing-rules.md) for Fibonacci, floor pivots, prior periods, '
        'support/resistance, price channels, patterns and divergence.']
    path = ROOT / 'docs' / 'indicators.md'
    path.write_text('\n\n'.join(sections)+'\n', encoding='utf-8')
    print(f'Exported metadata for {len(catalog)} indicator series to docs/indicators.md')


if __name__ == '__main__':
    main()
